def icon(name, color, sign):
    base = COLORS[color]
    image = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = image.load()
    for y in range(16):
        for x in range(16):
            d = math.hypot(x - 7.5, y - 7.5)
            if d > 7.6:
                continue
            if d > 6.5:
                # the gem's rim, its color, darker below
                shade = 0.85 if y < 8 else 0.6
                px[x, y] = tuple(int(c * shade) for c in base) + (255,)
            else:
                # inside: dark, a little light up and to the left
                light = max(0.0, 1 - math.hypot(x - 5, y - 5) / 9)
                f = 0.22 + 0.25 * light
                px[x, y] = tuple(int(c * f) for c in base) + (255,)
    rows = [r for r in sign.strip('\n').split('\n')]
    for j, row in enumerate(rows):
        for i, ch in enumerate(row):
            x, y = 3 + i, 3 + j
            if x > 12 or y > 12:
                continue
            if ch == '#':
                px[x, y] = (255, 255, 255, 255)
            elif ch == '+':
                px[x, y] = tuple(min(255, int(c * 1.05) + 20) for c in base) + (255,)
    # a shine on the rim
    px[4, 2] = (255, 255, 255, 200)
    px[3, 3] = (255, 255, 255, 160)
    image.save(OUT + name + '.png')


def lock():
    """A small padlock (for spells not learnt yet)."""
    image = Image.new('RGBA', (12, 12), (0, 0, 0, 0))
    px = image.load()
    for x in range(3, 9):
        px[x, 1] = (210, 210, 210, 255)
    for y in range(2, 5):
        px[3, y] = (210, 210, 210, 255)
        px[8, y] = (210, 210, 210, 255)
    for y in range(5, 11):
        for x in range(2, 10):
            px[x, y] = (230, 186, 70, 255) if y < 10 else (170, 130, 40, 255)
    px[5, 7] = px[6, 7] = (60, 40, 10, 255)
    px[5, 8] = px[6, 8] = (60, 40, 10, 255)
    image.save(OUT + 'lock.png')


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for name, (color, sign) in SIGNS.items():
        icon(name, color, sign)
    lock()
    print('wrote', len(SIGNS), 'pictures and a lock')
